package com.kuronami.musicdiscmaker.lavaplayer;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * YouTube の自動生成された配信曲で使われる、限定したクレジット形式を取り出す。
 *
 * <p>説明欄は利用者に見える文字列なので、それだけで真正性を保証することはできない。
 * この parser は複数の信号を同時に要求し、1つでも欠けた場合は結果を返さない。
 * 手がかりは {@code 曲名 · アーティスト( · アーティスト)} 形の冒頭クレジット行で、
 * {@code Artist:} 行が並ぶ旧形式では両者の完全一致を要求する
 * (2026-09-26 実測: 現在の説明欄は {@code Artist:} 行を持たない形式が主流)。</p>
 */
public final class YoutubeMusicMetadata {
    static final int MAX_TITLE_LENGTH = 512;
    static final int MAX_AUTHOR_LENGTH = 512;
    static final int MAX_DESCRIPTION_LENGTH = 64 * 1024;
    private static final int MAX_ARTISTS = 16;
    private static final String TOPIC_SUFFIX = " - Topic";
    private static final String PROVIDED_PREFIX = "Provided to YouTube by ";
    private static final String GENERATED_MARKER = "Auto-generated by YouTube.";
    private static final String CREDIT_SEPARATOR = " · ";
    private static final String ARTIST_PREFIX = "Artist: ";

    private YoutubeMusicMetadata() {
    }

    public static Optional<Value> fromDescription(
            String rawTitle, String rawAuthor, String shortDescription) {
        if (!isBounded(rawTitle, MAX_TITLE_LENGTH)
                || !isBounded(rawAuthor, MAX_AUTHOR_LENGTH)
                || !isBounded(shortDescription, MAX_DESCRIPTION_LENGTH)) {
            return Optional.empty();
        }

        String title = rawTitle.trim();
        String author = rawAuthor.trim();
        if (title.isEmpty() || !isTopicAuthor(author)) {
            return Optional.empty();
        }

        List<String> lines = nonBlankLines(shortDescription);
        if (lines.size() < 3
                || !isProviderLine(lines.get(0))
                || !GENERATED_MARKER.equals(lines.get(lines.size() - 1))) {
            return Optional.empty();
        }

        String creditPrefix = title + CREDIT_SEPARATOR;
        String creditLine = lines.get(1);
        if (!creditLine.startsWith(creditPrefix)) {
            return Optional.empty();
        }

        String artistCredit = creditLine.substring(creditPrefix.length());
        List<String> creditedArtists = parseArtists(artistCredit);
        List<String> declaredArtists = declaredArtists(lines);
        // 2026-09-26 実測: 現在の自動生成説明欄は Artist: 行を持たず、
        // 「曲名 · アーティスト( · アーティスト)」のクレジット行だけが配信情報を持つ
        // (The Weeknd / Macarena 等の実 watch 本文)。Artist: 行が存在する旧形式では
        // クレジットとの完全一致を引き続き要求し、行が無い新形式はクレジット行を採用する。
        if (creditedArtists.isEmpty()
                || (!declaredArtists.isEmpty() && !creditedArtists.equals(declaredArtists))) {
            return Optional.empty();
        }
        return Optional.of(new Value(title, creditedArtists));
    }

    private static boolean isBounded(String value, int maximumLength) {
        return value != null && value.length() <= maximumLength;
    }

    private static boolean isTopicAuthor(String author) {
        return author.endsWith(TOPIC_SUFFIX)
                && author.length() > TOPIC_SUFFIX.length()
                && !author.substring(0, author.length() - TOPIC_SUFFIX.length()).isBlank();
    }

    private static boolean isProviderLine(String line) {
        return line.startsWith(PROVIDED_PREFIX) && line.length() > PROVIDED_PREFIX.length();
    }

    private static List<String> nonBlankLines(String description) {
        List<String> lines = new ArrayList<>();
        description.lines()
                .map(String::trim)
                .filter(line -> !line.isEmpty())
                .forEach(lines::add);
        return lines;
    }

    private static List<String> parseArtists(String credit) {
        String[] parts = credit.split(CREDIT_SEPARATOR, -1);
        if (parts.length == 0 || parts.length > MAX_ARTISTS) {
            return List.of();
        }

        List<String> artists = new ArrayList<>(parts.length);
        for (String part : parts) {
            String artist = part.trim();
            if (artist.isEmpty() || artist.length() > MAX_AUTHOR_LENGTH) {
                return List.of();
            }
            artists.add(artist);
        }
        return List.copyOf(artists);
    }

    private static List<String> declaredArtists(List<String> lines) {
        List<String> artists = new ArrayList<>();
        for (int index = 2; index < lines.size() - 1; index++) {
            String line = lines.get(index);
            if (!line.startsWith(ARTIST_PREFIX)) {
                continue;
            }
            String artist = line.substring(ARTIST_PREFIX.length()).trim();
            if (artist.isEmpty() || artist.length() > MAX_AUTHOR_LENGTH || artists.size() == MAX_ARTISTS) {
                return List.of();
            }
            artists.add(artist);
        }
        return List.copyOf(artists);
    }

    public record Value(String title, List<String> artists) {
        public Value {
            if (title == null || title.isBlank()) {
                throw new IllegalArgumentException("title must not be blank");
            }
            artists = List.copyOf(artists);
            if (artists.isEmpty() || artists.stream().anyMatch(artist -> artist == null || artist.isBlank())) {
                throw new IllegalArgumentException("artists must not contain blank values");
            }
        }
    }
}
