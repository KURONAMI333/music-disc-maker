package com.kuronami.musicdiscmaker.lavaplayer;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.Set;
import org.junit.jupiter.api.Test;

/**
 * 2026-09-26 独立受入レビューの指摘 (R1〜R5 / P1 / P2 / P4) の回帰テスト。
 * 各テストはレビューで実演された反例を固定し、対照として維持すべき挙動も束ねる。
 */
class MetadataReviewFindingsTest {

    private static void assertBoth(String title, String author,
            String expectedTitle, String expectedAuthor) {
        MusicLoaderImpl.SourceMetadata meta = MusicLoaderImpl.sourceMetadata(
                title, author, YoutubeWatchPage.Result.EMPTY);
        assertEquals(expectedTitle, meta.displayTitle());
        assertEquals(expectedAuthor, meta.displayAuthor());
        assertEquals(expectedTitle, meta.searchTitle());
        assertEquals(expectedAuthor, meta.searchAuthor());
    }

    private static YoutubeWatchPage.Result watch(String title, String author, String description) {
        return new YoutubeWatchPage.Result(200_000L, title, author, description);
    }

    private static String creditOnlyDescription(String creditLine) {
        return "Provided to YouTube by Label\n\n" + creditLine + "\n\nAuto-generated by YouTube.";
    }

    // R1: 「SONG - ARTIST【credit】」の反転判定は、列挙クレジット括弧の中身が
    // 投稿者名を共有する時だけ発火する。括弧が投稿者を指さないなら従来の向きのまま。
    @Test
    void separatorDoesNotFlipWhenBracketDoesNotNameUploader() {
        assertBoth("A - Music【a/b】", "Music Channel", "Music", "A");
        assertBoth("X - Song【a/b】", "Song Channel", "Song", "X");
    }

    @Test
    void separatorStillFlipsWhenBracketNamesUploader() {
        // 2026-09-26 実測 (TGJ9-1LWFtE): 括弧内が投稿者名を共有する見出し型は
        // 引き続き左右を入れ替える。
        assertBoth("【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "ぽ", "Omaru Polka");
    }

    // R2: "|| 再掲尾" の除去は投稿者名の先頭語との一致を要求する。
    // 「Sky ⊂ Skylines」のような部分文字列では削らない。
    @Test
    void pipeTailRequiresUploaderWordPrefix() {
        assertBoth("Cities || Skylines", "Sky", "Cities || Skylines", "Sky");
        assertBoth("Song || Live Version", "Live", "Song || Live Version", "Live");
        // 維持 (2026-09-26 実測 7WXVFl-N6-o): 投稿者名の先頭と一致する再掲尾は削る
        assertBoth("【ORIGINAL MV】R x R x R || HAKOS BAELZ",
                "Hakos Baelz Ch. hololive", "R x R x R", "Hakos Baelz Ch. hololive");
    }

    // R3: / 列挙括弧は複数形・Side 等の版目印を含むなら曲名として保持する。
    @Test
    void enumeratedBracketWithVersionMarkersIsKept() {
        assertBoth("Artist - Song (Remixes/X)", "Uploader", "Song (Remixes/X)", "Artist");
        assertBoth("Artist - Song (Side A/Side B)", "Uploader", "Song (Side A/Side B)", "Artist");
        // 対照: 版目印を持たない列挙括弧は従来どおりクレジットとして落とす
        assertBoth("Artist - Song (Credit One/Credit Two)", "Uploader", "Song", "Artist");
    }

    // R4: 構造化クレジットの採用経路でも、cleaner と同じ前置き除去を掛けて
    // 説明欄の有無で表示・検索が変わらないようにする。
    @Test
    void structuredCreditTitleGetsSamePrefixCleanup() {
        YoutubeWatchPage.Result result = watch("Adele - Hello", "Adele - Topic",
                creditOnlyDescription("Adele - Hello · Adele"));
        MusicLoaderImpl.SourceMetadata meta = MusicLoaderImpl.sourceMetadata(
                "Adele - Hello", "Adele - Topic", result);

        assertEquals("Hello", meta.displayTitle());
        assertEquals("Adele", meta.displayAuthor());
        assertEquals("Hello", meta.searchTitle());
        assertEquals("Adele", meta.searchAuthor());
    }

    // R5: "(Cover by X)" の投稿者帰属は語境界での一致を要求する。
    // 1 語のチャンネル名が他人名の一部に現れるだけでは帰属しない。
    @Test
    void coverByAttributionRequiresWordLevelMatch() {
        assertBoth("X - Song (Cover by Someone Famous)", "Famous",
                "Song (Cover by Someone Famous)", "X");
        // 維持 (2026-09-26 実測 5GQnC6UUsZw): 投稿者の複合名が語として含まれるなら
        // カバー実行者として帰属する
        assertBoth("Adele - Hello (Cover by Taka from ONE OK ROCK)", "ONE OK ROCK",
                "Hello (Cover by Taka from ONE OK ROCK)", "ONE OK ROCK");
    }

    // P1: 版の目印探しは CJK 目印にも語境界を要求する。
    // 「ホロライブ」の中の「ライブ」を目印としない。
    @Test
    void variantMarkersRespectKatakanaBoundaries() {
        assertEquals(Set.of(), TrackMatch.variantMarkers(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】"));
        assertEquals(Set.of(), TrackMatch.variantMarkers("ぽ【ホロライブ】"));
        // 対照: 目印が独立して現れた時は従来どおり拾う
        assertEquals(Set.of("ライブ"), TrackMatch.variantMarkers("Song【ライブ】"));
        assertEquals(Set.of("歌ってみた"), TrackMatch.variantMarkers("Song【歌ってみた】"));
        assertEquals(Set.of("live"), TrackMatch.variantMarkers("Song (Live)"));
    }

    // P1 + P4: 見出し型のソースが、正しい同一録音候補と照合できる。
    @Test
    void headingFormSourceMatchesSameRecordingCandidates() {
        assertTrue(TrackMatch.sameRecording(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "ぽ", "Omaru Polka"));
        assertTrue(TrackMatch.sameRecording(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "ぽ - Omaru Polka", "Omaru Polka"));
    }

    @Test
    void headingFormSourceStillRejectsWrongRecordings() {
        // 対照: 別アーティスト・別曲・別版の候補は拾わない
        assertFalse(TrackMatch.sameRecording(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "ぽ", "Someone Else"));
        assertFalse(TrackMatch.sameRecording(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "Different Song", "Omaru Polka"));
        assertFalse(TrackMatch.sameRecording(
                "【ORIGINAL SONG+MV】ぽ - Omaru Polka【尾丸ポルカ/ホロライブ/4K】",
                "Polka Ch. 尾丸ポルカ", "ぽ (Live)", "Omaru Polka"));
    }

    // P2: clean() 側も display() と同じく「曲名 - 録音版」を逆向きに割らない。
    @Test
    void cleanKeepsRecordingSuffixTitlesWhole() {
        assertBoth("Song - Live", "Artist", "Song - Live", "Artist");
        assertBoth("Song - Remix", "Artist", "Song - Remix", "Artist");
        // 対照: 通常の「ARTIST - SONG」は従来どおり分ける
        assertBoth("Adele - Hello", "Hello Channel", "Hello", "Adele");
    }

    // P4: 括弧を持たない平面「SONG - ARTIST」は、右側が投稿者名と正規化後に
    // 一致する時だけ左右を入れ替える (投稿者と確かに一致する場合に限定)。
    @Test
    void flatSongArtistFlipsOnlyWhenRightIsUploader() {
        assertBoth("ぽ - Omaru Polka", "Omaru Polka", "ぽ", "Omaru Polka");
        // 対照: 右側が投稿者と一致しない標準形は従来どおりの向き
        assertBoth("Adele - Hello", "Hello Channel", "Hello", "Adele");
        // 「曲名 - 版」は録音版ガードで反転も分割もしない
        assertBoth("Song - Live", "Live", "Song - Live", "Live");
    }
}
