package com.kuronami.musicdiscmaker.lavaplayer;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.StringReader;
import org.junit.jupiter.api.Test;

class YoutubeMetadataIntegrationTest {
    private static final String VIDEO_ID = "bnlodp7ftlU";
    private static final String RELEASE_DESCRIPTION = """
            Provided to YouTube by Kontor New Media GmbH

            Раз, Два, Три! · ПЕРВОКУРСНИК

            Released on: 2024-04-05
            Artist: ПЕРВОКУРСНИК
            Composer, Lyricist: Константинов Вячеслав Демьянович

            Auto-generated by YouTube.
            """;

    @Test
    void readsBoundedVideoDetailsAndUsesReleaseCredit() throws Exception {
        String page = watchPage(VIDEO_ID, "Раз, Два, Три!", "Release - Topic",
                RELEASE_DESCRIPTION, "178");

        YoutubeWatchPage.Result watch = YoutubeWatchPage.scan(
                new StringReader(page), VIDEO_ID, System.currentTimeMillis() + 1_000L);
        MusicLoaderImpl.SourceMetadata metadata = MusicLoaderImpl.sourceMetadata(
                "Раз, Два, Три!", "Release - Topic", watch);

        assertEquals(178_000L, watch.durationMs());
        assertEquals("Раз, Два, Три!", metadata.displayTitle());
        assertEquals("ПЕРВОКУРСНИК", metadata.displayAuthor());
        assertEquals("Раз, Два, Три!", metadata.searchTitle());
        assertEquals("ПЕРВОКУРСНИК", metadata.searchAuthor());
    }

    @Test
    void rejectsVideoDetailsForAnotherVideoId() throws Exception {
        YoutubeWatchPage.Result result = YoutubeWatchPage.scan(
                new StringReader(watchPage("aaaaaaaaaaa", "Song", "Artist - Topic",
                        generatedDescription("Song", "Artist"), "120")),
                VIDEO_ID,
                System.currentTimeMillis() + 1_000L);

        assertEquals(YoutubeWatchPage.Result.EMPTY, result);
    }

    @Test
    void ambiguousGenericTopicFallsBackWithoutInventingAnArtist() {
        MusicLoaderImpl.SourceMetadata release = MusicLoaderImpl.sourceMetadata(
                "Unknown Song", "Release - Topic", YoutubeWatchPage.Result.EMPTY);
        MusicLoaderImpl.SourceMetadata various = MusicLoaderImpl.sourceMetadata(
                "Unknown Song", "Various Artists - Topic", YoutubeWatchPage.Result.EMPTY);

        assertEquals("Unknown Song", release.displayTitle());
        assertEquals("", release.displayAuthor());
        assertEquals("", release.searchAuthor());
        assertEquals("", various.displayAuthor());
        assertEquals("", various.searchAuthor());
    }

    @Test
    void ordinaryReleaseUploaderIsNotTreatedAsGenericTopic() {
        MusicLoaderImpl.SourceMetadata metadata = MusicLoaderImpl.sourceMetadata(
                "Release - New Song (Live)", "Release", YoutubeWatchPage.Result.EMPTY);

        assertEquals("New Song (Live)", metadata.displayTitle());
        assertEquals("Release", metadata.displayAuthor());
    }

    @Test
    void displayKeepsVersionAndCreditTextWhileSearchNormalizationRemainsSeparate() {
        MusicLoaderImpl.SourceMetadata metadata = MusicLoaderImpl.sourceMetadata(
                "Artist - Song (Live Remix) feat. Guest [Official Audio]",
                "Uploader",
                YoutubeWatchPage.Result.EMPTY);

        assertEquals("Song (Live Remix) feat. Guest", metadata.displayTitle());
        assertEquals("Artist", metadata.displayAuthor());
        assertEquals("Song (Live Remix)", metadata.searchTitle());
        assertEquals("Artist", metadata.searchAuthor());
    }

    @Test
    void oversizedDescriptionCannotBecomeTrustedMetadata() throws Exception {
        String huge = "x".repeat(YoutubeMusicMetadata.MAX_DESCRIPTION_LENGTH + 1);
        YoutubeWatchPage.Result watch = YoutubeWatchPage.scan(
                new StringReader(watchPage(VIDEO_ID, "Song", "Release - Topic", huge, "120")),
                VIDEO_ID,
                System.currentTimeMillis() + 1_000L);

        assertEquals("", watch.shortDescription());
        assertEquals("", MusicLoaderImpl.sourceMetadata(
                "Song", "Release - Topic", watch).displayAuthor());
    }

    @Test
    void invalidOrExpiredScanInputReturnsEmpty() throws Exception {
        assertEquals(YoutubeWatchPage.Result.EMPTY,
                YoutubeWatchPage.scan(new StringReader("{}"), "short", Long.MAX_VALUE));
        assertEquals(YoutubeWatchPage.Result.EMPTY,
                YoutubeWatchPage.scan(new StringReader("{}"), VIDEO_ID, 0L));
        assertTrue(YoutubeWatchPage.fetch("https://example.com/watch?v=" + VIDEO_ID, 100L)
                .equals(YoutubeWatchPage.Result.EMPTY));
    }

    @Test
    void cleansObservedPromotionalHeadingsWithoutRemovingNamesOrRecordingVersions() {
        assertDisplay("Official髭男dism - Pretender［Official Video］", "Official髭男dism",
                "Pretender", "Official髭男dism");
        assertDisplay("YOASOBI「アイドル」 Official Music Video", "YOASOBI", "アイドル", "YOASOBI");
        assertDisplay("【Ado】うっせぇわ", "Ado", "うっせぇわ", "Ado");
        assertDisplay("【オリジナル曲】Artist「Song」", "Artist", "Song", "Artist");
        assertDisplay("【ORIGINAL MV】Song", "Artist", "Song", "Artist");
        assertDisplay("【ORIGINAL SONG+MV】Song", "Artist", "Song", "Artist");
        assertDisplay("【正式な曲名】", "Artist", "【正式な曲名】", "Artist");
        assertDisplay("Song - Live", "Artist", "Song - Live", "Artist");
        assertDisplay("Artist「Song」 (Live) feat. Guest / Alternative", "Artist",
                "Song (Live) feat. Guest / Alternative", "Artist");
        assertDisplay("Artist - Song [Official Live Video]", "Artist",
                "Song [Official Live Video]", "Artist");
        assertDisplay("【オリジナル曲】", "Artist - Topic", "【オリジナル曲】", "Artist");
    }

    private static void assertDisplay(String title, String author, String expectedTitle, String expectedAuthor) {
        MusicLoaderImpl.SourceMetadata result = MusicLoaderImpl.sourceMetadata(title, author, YoutubeWatchPage.Result.EMPTY);
        assertEquals(expectedTitle, result.displayTitle());
        assertEquals(expectedAuthor, result.displayAuthor());
    }

    private static String generatedDescription(String title, String artist) {
        return "Provided to YouTube by Label\n\n"
                + title + " · " + artist + "\n\n"
                + "Artist: " + artist + "\n\n"
                + "Auto-generated by YouTube.";
    }

    private static String watchPage(String videoId, String title, String author,
            String description, String seconds) {
        return "<html><script>var ytInitialPlayerResponse={\"videoDetails\":"
                + jsonObject(videoId, title, author, description, seconds)
                + ",\"other\":{\"brace\":\"} inside a string\"}};</script></html>";
    }

    private static String jsonObject(String videoId, String title, String author,
            String description, String seconds) {
        return "{\"videoId\":\"" + escape(videoId)
                + "\",\"title\":\"" + escape(title)
                + "\",\"author\":\"" + escape(author)
                + "\",\"shortDescription\":\"" + escape(description)
                + "\",\"lengthSeconds\":\"" + escape(seconds) + "\"}";
    }

    private static String escape(String value) {
        return value.replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\r", "\\r")
                .replace("\n", "\\n");
    }
}
