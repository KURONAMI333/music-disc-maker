package com.kuronami.musicdiscmaker.lavaplayer;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

class YoutubeMusicMetadataTest {
    @Test
    void extractsObservedReleaseTopicMetadata() {
        String description = """
                Provided to YouTube by Kontor New Media GmbH

                Раз, Два, Три! · ПЕРВОКУРСНИК

                Раз, Два, Три!

                ℗ ALLIANCE MUSIC GROUP LLP

                Released on: 2024-04-05

                Artist: ПЕРВОКУРСНИК
                Composer, Lyricist: Константинов Вячеслав Демьянович

                Auto-generated by YouTube.
                """;

        var result = YoutubeMusicMetadata.fromDescription(
                "Раз, Два, Три!", "Release - Topic", description).orElseThrow();

        assertEquals("Раз, Два, Три!", result.title());
        assertEquals(List.of("ПЕРВОКУРСНИК"), result.artists());
    }

    @Test
    void extractsOrdinaryTopicWithoutOptionalMetadataTags() {
        String description = """
                Provided to YouTube by Example Distributor

                Song - Live (Official) · Artist Name

                Artist: Artist Name

                Auto-generated by YouTube.
                """;

        var result = YoutubeMusicMetadata.fromDescription(
                "Song - Live (Official)", "Artist Name - Topic", description).orElseThrow();

        assertEquals("Song - Live (Official)", result.title());
        assertEquals(List.of("Artist Name"), result.artists());
    }

    @Test
    void preservesMultipleArtists() {
        String description = generatedDescription(
                "Collaboration · Artist One · Artist Two",
                "Artist One",
                "Artist Two");

        var result = YoutubeMusicMetadata.fromDescription(
                "Collaboration", "Various Artists - Topic", description).orElseThrow();

        assertEquals(List.of("Artist One", "Artist Two"), result.artists());
    }

    @Test
    void rejectsFreeFormArtistLineWithoutLeadingCredit() {
        String description = """
                Provided to YouTube by Claimed Distributor

                Artist: Claimed Artist

                Song

                Auto-generated by YouTube.
                """;

        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song", "Claimed Artist - Topic", description).isEmpty());
    }

    @Test
    void rejectsLeadingCreditWithoutDeclaredArtistLine() {
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song", "Artist - Topic", generatedDescription("Song · Artist")).isEmpty());
    }

    @Test
    void rejectsWhenAnyAutoGeneratedTopicSignalIsMissing() {
        String validDescription = generatedDescription("Song · Artist", "Artist");
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song", "Ordinary Uploader", validDescription).isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song",
                "Artist - Topic",
                validDescription.replace("Provided to YouTube by Label", "Uploaded by Label")).isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song",
                "Artist - Topic",
                validDescription.replace("Auto-generated by YouTube.", "Thanks for listening.")).isEmpty());
    }

    @Test
    void rejectsCreditWhoseTitleDoesNotMatchVideoTitle() {
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Original Song", "Artist - Topic", generatedDescription("Other Song · Artist", "Artist")).isEmpty());
    }

    @Test
    void rejectsCreditTokensThatAreNotDeclaredAsArtists() {
        String description = """
                Provided to YouTube by Label

                Song · Artist · Composer Name

                Artist: Artist
                Composer: Composer Name

                Auto-generated by YouTube.
                """;

        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song", "Artist - Topic", description).isEmpty());
    }

    @Test
    void preservesMiddleDotInsideTitle() {
        var result = YoutubeMusicMetadata.fromDescription(
                "Part One · Part Two",
                "Artist - Topic",
                generatedDescription("Part One · Part Two · Artist", "Artist")).orElseThrow();

        assertEquals("Part One · Part Two", result.title());
        assertEquals(List.of("Artist"), result.artists());
    }

    @Test
    void acceptsCrLfAndSurroundingBlankLines() {
        String description = "\r\nProvided to YouTube by Label\r\n\r\nSong · Artist\r\n\r\nArtist: Artist\r\n\r\nAuto-generated by YouTube.\r\n\r\n";

        var result = YoutubeMusicMetadata.fromDescription(
                " Song ", " Artist - Topic ", description).orElseThrow();

        assertEquals("Song", result.title());
        assertEquals(List.of("Artist"), result.artists());
    }

    @Test
    void rejectsNullAndOversizedInputs() {
        assertTrue(YoutubeMusicMetadata.fromDescription(null, "Artist - Topic", "description").isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription("Song", null, "description").isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription("Song", "Artist - Topic", null).isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song",
                "Artist - Topic",
                "x".repeat(YoutubeMusicMetadata.MAX_DESCRIPTION_LENGTH + 1)).isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "x".repeat(YoutubeMusicMetadata.MAX_TITLE_LENGTH + 1),
                "Artist - Topic",
                generatedDescription("Song · Artist", "Artist")).isEmpty());
        assertTrue(YoutubeMusicMetadata.fromDescription(
                "Song",
                "x".repeat(YoutubeMusicMetadata.MAX_AUTHOR_LENGTH + 1),
                generatedDescription("Song · Artist", "Artist")).isEmpty());
    }

    @Test
    void valueDefensivelyCopiesArtists() {
        var mutableArtists = new java.util.ArrayList<>(List.of("Artist"));
        var value = new YoutubeMusicMetadata.Value("Song", mutableArtists);

        mutableArtists.set(0, "Changed");

        assertEquals(List.of("Artist"), value.artists());
    }

    private static String generatedDescription(String creditLine, String... artists) {
        var description = new StringBuilder("Provided to YouTube by Label\n\n")
                .append(creditLine)
                .append('\n');
        for (String artist : artists) {
            description.append("\nArtist: ").append(artist).append('\n');
        }
        return description.append("\nAuto-generated by YouTube.").toString();
    }
}
